"""The Faner part of the manuscript's number and figure pipeline, re-run on the radius-1.5 histories.

What the pipeline needs for Faner (read from the repository, unchanged definitions):
* the macros: paper/01_particle_jfpe/regen/check_core2_particle_results.py, ladder_main, the Faner keys and their
  formats (FanerDryTime .1f, FanerCrossTwenty .1f, FanerFallingInterval .1f, FanerExitHexane .3g, FanerExitWater .3g,
  FanerExitTemperature .1f, FanerFreeEnd .1f, FanerFallingShortfall .0f, FanerMaxBeta .3f,
  FanerLastHolderClockTemperature .1f, FanerMaxBetaAfterBirth .2f, FanerCells, FanerAuditMax .1e), the values from
  export_ladder_histories_157.py's faner_numbers (a01_read.observables reproduces them);
* the figure history: the CSV columns of export_ladder_histories_157.py (t_s, hexane_kg_kg_dry, water_kg_kg_dry,
  mean_temperature_k, surface_water_kg_kg_dry, front_z, stage), the rows of its read_case;
* the figures: fig_particle_experiments.py draw(), its Faner panels (fig_faner_particle_history_core2 and
  fig_faner_supporting_states), copied here with one adaptation: the bath is the measured vapour trace, so the
  former "Prescribed vapour: 120 C" line is not drawn and the measured vapour line is labelled as the prescribed
  bath; styles, axes and markers unchanged.
The adopted Faner history uses 40 radial cells; DT uses 80. The Faner refinement ladder contains 10, 20 and 40 cells, with matched half-step checks at 20 and 40 cells.
Writes tables/r15/pipeline/: faner_numbers_r15.tex, faner_numbers_r15.json (every value at full precision with
the input sha256), faner_history_r15.csv and the two figures (.pdf, .png).
usage: f01_faner_pipeline_r15.py
"""

import argparse
import csv
import hashlib
import json
import math
import sys
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

sys.path.insert(0, str(Path(__file__).resolve().parent))
import faner_history_reader as r  # noqa: E402

r.RADIUS = 0.0015

ROOT = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser(description="Regenerate the adopted Faner numbers, loading scores and figures.")
parser.add_argument("--case", type=Path, default=ROOT / "paper/analysis/results_v1.4.0/Faner_R15_N40_L1")
parser.add_argument("--out", type=Path, default=ROOT / "reruns/faner_figures")
args = parser.parse_args()
folder = args.case.resolve()
R2 = folder.parent
reported = folder.name
OUT = args.out.resolve()
OUT.mkdir(parents=True, exist_ok=True)
COLORS = {"hexane": "#885184", "water": "#1689b0", "temperature": "#b65e32"}
case_record = json.loads((folder / "case.json").read_text(encoding="utf-8"))
assert case_record["complete_history"] and case_record["sources_unchanged_during_run"]
cells = case_record["base_cells"]
audit_path = folder / "independent_whole_history_audit.json"
if not audit_path.exists():
    audit_path = folder.with_suffix(".independent_audit.json")
c = r.read_case(folder)
f = r.observables(c)
audit = json.loads((audit_path).read_text(encoding="utf-8"))
assert audit["passed"] and audit["complete_history"]
values = {
    "FanerDryTime": f"{f['FanerDryTime_s']:.1f}",
    "FanerCrossTwenty": f"{f['FanerCrossTwenty_s']:.1f}",
    "FanerFallingInterval": f"{f['FanerFallingInterval_s']:.1f}",
    "FanerExitHexane": f"{f['FanerExitHexane_kg_kg_dry']:.3g}",
    "FanerExitWater": f"{f['FanerExitWater_kg_kg_dry']:.3g}",
    "FanerExitTemperature": f"{f['FanerExitTemperature_C']:.1f}",
    "FanerFreeEnd": f"{f['FanerFreeEnd_s']:.1f}",
    "FanerFallingShortfall": f"{f['FanerFallingShortfall_pct']:.0f}",
    "FanerMaxBeta": f"{f['FanerMaxBeta']:.3f}",
    "FanerLastHolderClockTemperature": f"{f['FanerLastHolderClockTemperature_C']:.1f}",
    "FanerMaxBetaAfterBirth": f"{f['max_abs_beta_after_birth']:.2f}",
    "FanerCells": str(cells),
    "FanerAuditMax": f"{max(audit['maximum_independent_normalized_W_H_U']):.1e}".replace("e-", "\\times10^{-") + "}",
}
inputs = {p.name: hashlib.sha256(p.read_bytes()).hexdigest() for p in
          (folder / "case.json", folder / "birth.json", folder / "front.history.jsonl", folder / "dry.history.jsonl",
           audit_path)}
(OUT / "faner_numbers_r15.tex").write_text(
    "% Generated by f01_faner_pipeline_r15.py (radius 1.5 mm, measured vapour trace, phi_A 0.29; "
    f"reported rung {reported}).\n" + "".join(f"\\newcommand{{\\{k}}}{{{v}}}\n" for k, v in values.items()),
    encoding="utf-8", newline="\n")
(OUT / "faner_numbers_r15.json").write_text(json.dumps({
    "reported": reported, "macros": values, "full_precision": f, "audit_max_W_H_U": audit["maximum_independent_normalized_W_H_U"],
    "input_sha256": inputs, "script_sha256": hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
    "physically_qualifying": False}, indent=1, default=str), encoding="utf-8")

# the figure history, in the export's columns (water = particle water; surface water = outer cell retained water)
rows = []
for row in json.loads((folder / "birth.json").read_text(encoding="utf-8"))["feed_rows"]:
    rows.append({"t_s": row["t_s"], "hexane_kg_kg_dry": row["hexane_kg_kg_dry"], "water_kg_kg_dry": row["retained_water_kg_kg_dry"],
                 "mean_temperature_k": row["temperature_k"], "surface_water_kg_kg_dry": "", "front_z": 1.0, "stage": "attached"})
for name, stage in (("front.history.jsonl", "radial"), ("dry.history.jsonl", "stationary dry")):
    for line in (folder / name).read_text(encoding="utf-8").splitlines():
        x = json.loads(line)
        if x["kind"] in ("refusal", "initial") or x["time_s"] <= rows[-1]["t_s"]:
            continue
        cw = x.get("retained_water_cells_kg_kg_dry")
        rows.append({"t_s": x["time_s"], "hexane_kg_kg_dry": x["hexane_kg_kg_dry"], "water_kg_kg_dry": x["particle_water_kg_kg_dry"],
                     "mean_temperature_k": x["temperature_k"], "surface_water_kg_kg_dry": cw[-1] if cw else "",
                     "front_z": x["front_z"] if x.get("front_z") is not None else (0.0 if stage == "stationary dry" else ""),
                     "stage": stage})
assert rows[0]["t_s"] == 0 and abs(rows[-1]["t_s"] - 240) < 1e-9
cols = ["t_s", "hexane_kg_kg_dry", "water_kg_kg_dry", "mean_temperature_k", "surface_water_kg_kg_dry", "front_z", "stage"]
with (OUT / "faner_history_r15.csv").open("w", newline="", encoding="utf-8") as s:
    w = csv.DictWriter(s, fieldnames=cols)
    w.writeheader()
    w.writerows(rows)

plt.rcParams.update({"font.size": 9, "axes.labelsize": 9, "legend.fontsize": 8, "axes.spines.top": False,
                     "axes.spines.right": False, "pdf.fonttype": 42, "axes.linewidth": 0.7})


def save(fig, stem):
    for ext in ("pdf", "png"):
        fig.savefig(OUT / f"{stem}.{ext}", dpi=220)
    plt.close(fig)


def measured(quantity):
    base = r.MAIN / "paper/analysis/datasets/faner2019_v2"
    with (base / "adjudication_per_point.csv").open(newline="", encoding="utf-8") as stream:
        bands = {x["point_id"]: float(x["uncertainty_abs"]) for x in csv.DictReader(stream)}
    with (base / "curves.csv").open(newline="", encoding="utf-8") as stream:
        return sorted((float(x["time_s"]), float(x["value"]), bands[x["point_id"]]) for x in csv.DictReader(stream)
                      if x["figure"] == "2" and x["material"] == "soybean" and x["temperature_c"] == "120"
                      and x["quantity"] == quantity and x["series"] == "experimental" and not x["superseded_by"])


faner = rows
fig, axes = plt.subplots(2, 1, figsize=(6.8, 5.4), sharex=True, layout="constrained")
t = [x["t_s"] for x in faner]
axes[0].plot(t, [x["hexane_kg_kg_dry"] for x in faner], color=COLORS["hexane"], lw=1.7, label="Particle model")
axes[1].plot(t, [x["mean_temperature_k"] - 273.15 for x in faner], color=COLORS["temperature"], lw=1.7, label="Particle model")
for ax, quantity, label in zip(axes, ("solvent_loading", "particle_temperature"), ("Faner experiment", "Faner experiment")):
    data = measured(quantity)
    ax.errorbar(*zip(*[(x[0], x[1]) for x in data]), yerr=[x[2] for x in data], fmt="o", ms=3.6, capsize=2,
                color="#303840", lw=0.8, label=label)
    ax.grid(False)
    ax.legend(loc="upper right" if ax is axes[0] else "lower right", frameon=False)
axes[0].set(ylabel="Hexane (kg/kg dry meal)", ylim=(0, 0.51), xlim=(0, 240))
axes[1].set(ylabel="Temperature (°C)", xlabel="Time from reported start (s)", ylim=(60, 124))
axes[0].text(0.025, 0.92, "(a)", transform=axes[0].transAxes, weight="bold")
axes[1].text(0.025, 0.81, "(b)", transform=axes[1].transAxes, weight="bold")
gas = measured("gas_temperature")
axes[1].plot([x[0] for x in gas], [x[1] for x in gas], color="0.35", ls="--", lw=0.9, label="Measured vapour (prescribed bath)")
axes[1].legend(loc="lower right", frameon=False)
save(fig, "fig_faner_particle_history_core2")
fig, axes = plt.subplots(2, 1, figsize=(6.8, 4.2), sharex=True, layout="constrained")
axes[0].plot(t, [x["water_kg_kg_dry"] for x in faner], color=COLORS["water"], label="Particle water")
axes[0].plot(t, [x["surface_water_kg_kg_dry"] if x["surface_water_kg_kg_dry"] != "" else math.nan for x in faner],
             color=COLORS["water"], ls="--", label="Surface retained water")
axes[0].set_ylabel("Water (kg/kg dry meal)")
axes[0].legend(frameon=False)
axes[1].plot(t, [x["front_z"] if x["front_z"] != "" else math.nan for x in faner], color=COLORS["hexane"])
axes[1].set(ylabel="Liquid-core volume fraction", xlabel="Time from reported start (s)")
for ax in axes:
    ax.grid(alpha=0.15)
save(fig, "fig_faner_supporting_states")
print(json.dumps({"reported": reported, "macros": values}, indent=1))

# Ordinary loading SSE, with temperature reported separately.
scores = r.source_scores(c)
for quantity, value in scores.items():
    value["SSE"] = sum(d*d for d in value["deviations"])
(OUT / "source_scores.json").write_text(json.dumps(scores, indent=2) + "\n", encoding="utf-8")
