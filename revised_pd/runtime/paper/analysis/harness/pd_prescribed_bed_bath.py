"""Source-anchored PD gas prescription and bottom-heated bed exposure.

An offline engineering boundary construction, not measured PD composition or
a coupled washer/tower. Gas equilibrium uses native hexane fugacity and the
existing retained-water activity law; a separate integral PD energy balance
sets generated vapour flow. No purity or removal fraction is fitted.
"""

from dataclasses import asdict, dataclass, replace
import math

import numpy as np
from scipy.optimize import brentq, least_squares
from types import MappingProxyType, SimpleNamespace

import experiment_core2_dt_feed as feed
from particle_solver_configuration import ParticleModelParameters

core = feed.core
nc = feed.nc
kernel = feed.kernel


def pd_film_pair(source, radius_m=0.0015, *, transport_mode):
    """Evaluate the existing B.7--B.10 oracle at the generated PD flow.

    canonical_reference retains the canonical constant film-property priors,
    including its effective film-reference density. This is not the actual
    PD gas density (reported independently by source_gas). mixture_properties
    uses native mixture density/cp and retains the native low-Sc refusal.
    Neither mode alters the correlation or its admissibility guard.
    """
    reference = PdReference(**source["reference"])
    original = core.film_pair_at_radius(radius_m)
    y = source["y_hexane"]
    molar_mass = y * core.hx.M + (1 - y) * core.wa.M
    cp = nc.mixture_heat_capacity(source["temperature_k"], reference.pressure_pa, y).value_j_mol_k
    if transport_mode not in ("canonical_reference", "mixture_properties"):
        raise ValueError("explicit PD transport mode required")
    density = (
        source["gas_density_kg_m3"]
        if transport_mode == "mixture_properties"
        else original.state.gas_density_kg_m3
    )
    heat_capacity = (
        cp / molar_mass
        if transport_mode == "mixture_properties"
        else original.state.gas_heat_capacity_j_kg_k
    )
    state = replace(
        original.state,
        bed_void_fraction=1 - reference.bed_dry_density_kg_m3 / 1159.65,
        gas_density_kg_m3=density,
        gas_superficial_velocity_m_s=source["total_flow_kg_s"] / (density * reference.tray_area_m2),
        gas_heat_capacity_j_kg_k=heat_capacity,
        state_provenance=(
            "PD-generated vapour flow only; geometry voidage; "
            + transport_mode
            + "; inherited mu/k/D priors; reference density is not a measured PD density"
        ),
    )
    return core.bf.coletto_b7_b10_pair(state)


@dataclass(frozen=True)
class PdReference:
    duty_w: float = 2.3e6
    dry_inventory_kg: float = 12049.0
    residence_s: float = 490.20224190324825
    pressure_pa: float = 101325.0 - 98.0665
    tray_count: int = 3
    tray_diameter_m: float = 6.0
    bed_depth_m: float = 0.30
    bed_conductivity_w_m_k: float = 0.24

    def __post_init__(self):
        values = asdict(self)
        if any(isinstance(v, bool) or not math.isfinite(v) or v <= 0 for v in values.values()):
            raise ValueError("PD reference inputs must be finite and positive")
        if not isinstance(self.tray_count, int):
            raise ValueError("tray count must be an integer")

    @property
    def dry_flow_kg_s(self):
        return self.dry_inventory_kg / self.residence_s

    @property
    def mean_duty_w_kg_dry(self):
        return self.duty_w / self.dry_inventory_kg

    @property
    def tray_area_m2(self):
        return math.pi * self.tray_diameter_m**2 / 4

    @property
    def bed_dry_density_kg_m3(self):
        return self.dry_inventory_kg / (self.tray_count * self.tray_area_m2 * self.bed_depth_m)


def source_gas(bath, reference=PdReference()):
    """Close one integral PD source and retained-water/hexane equilibrium.

    Assumption: the local vapour is generated by representative wet meal,
    equilibrated with free hexane and RETAINED water at its exit loading.
    This is not the pure-water two-liquid co-boiling root. The incoming
    particle does not feed back into this offline prescribed source.
    """
    march = feed.FeedMarch(
        bath,
        0.0015,
        64,
        pressure_pa=reference.pressure_pa,
        property_parameters=ParticleModelParameters(),
    )
    initial_h = march.state.total_hexane_loading
    initial_w = march.state.retained_water_loading
    initial_u = march.total_energy / march.dry
    energy_input = reference.duty_w / reference.dry_flow_kg_s
    latest = {}

    def residual(x):
        temperature, y_h, removed_h = map(float, x)
        removed_w = removed_h / core.hx.M * (1 - y_h) / y_h * core.wa.M
        remaining_w = initial_w - removed_w
        wet = replace(march.wet, X_water=remaining_w)
        params = replace(march.params, wet_core=wet)
        state = core.sphere.initialize_qualified_feed(
            params,
            total_hexane_loading=initial_h - removed_h,
            temperature_k=temperature,
            retained_water_loading=remaining_w,
            oil_fraction=march.state.oil_fraction,
        )
        gas = core.bg.state(temperature, reference.pressure_pa, 1 - y_h, y_h)
        fh = core.hx.state_Tp(temperature, reference.pressure_pa, "liquid").fugacity
        fw = core.wa.state_Tp(temperature, reference.pressure_pa, "liquid").fugacity
        log_aw = core.sp.water_log_activity(remaining_w, core.sp.LuikovParams())
        hh = nc.hexane_partial_enthalpy(temperature, reference.pressure_pa, y_h).value_j_mol
        hw = nc.water_partial_enthalpy(temperature, reference.pressure_pa, y_h).value_j_mol
        exported_energy = removed_h / core.hx.M * hh + removed_w / core.wa.M * hw
        energy_residual = math.fsum(
            (state.total_internal_energy_j / march.dry, -initial_u, exported_energy, -energy_input)
        )
        r = np.array(
            (
                math.log(gas.fugacity_hexane_pa / fh),
                math.log(gas.fugacity_water_pa / fw) - log_aw,
                energy_residual / 2e5,
            )
        )
        latest.update(
            temperature_k=temperature,
            y_hexane=y_h,
            removed_hexane_kg_kg_dry=removed_h,
            removed_water_kg_kg_dry=removed_w,
            remaining_water_kg_kg_dry=remaining_w,
            water_activity=math.exp(log_aw),
            hexane_fugacity_ratio=gas.fugacity_hexane_pa / fh,
            water_fugacity_ratio=gas.fugacity_water_pa / fw,
            source_energy_residual_j_kg_dry=energy_residual,
            state_energy_j_kg_dry=state.total_internal_energy_j / march.dry,
            exported_energy_j_kg_dry=exported_energy,
            gas_density_kg_m3=(
                reference.pressure_pa
                / (core.bg.R * temperature * gas.compressibility)
                * ((1 - y_h) * core.wa.M + y_h * core.hx.M)
            ),
        )
        return r

    # Source-construction solve, not a new particle seed/retry family.
    result = least_squares(
        residual,
        [338.0, 0.84, 0.05],
        bounds=([334.5, 0.65, 0.0], [341.8, 0.99, 0.15]),
        xtol=1e-14,
        ftol=1e-14,
        gtol=None,
        jac="3-point",
        max_nfev=150,
    )
    r = residual(result.x)
    if not result.success or max(abs(r)) > 1e-10:
        raise RuntimeError(f"offline PD source construction refuses: {r.tolist()}")
    latest.update(
        reference=asdict(reference),
        initial_hexane_kg_kg_dry=initial_h,
        initial_water_kg_kg_dry=initial_w,
        initial_energy_j_kg_dry=initial_u,
        source_energy_input_j_kg_dry=energy_input,
        dry_flow_basis_kg_s=reference.dry_flow_kg_s,
        nominal_scenario_dry_flow_kg_s=25.0,
        closure_residuals=r.tolist(),
        physically_qualifying=False,
        assumption="offline equilibrium source over wet meal; indirect literature anchor, not measurement",
    )
    latest["hexane_flow_kg_s"] = reference.dry_flow_kg_s * latest["removed_hexane_kg_kg_dry"]
    latest["water_flow_kg_s"] = reference.dry_flow_kg_s * latest["removed_water_kg_kg_dry"]
    latest["total_flow_kg_s"] = latest["hexane_flow_kg_s"] + latest["water_flow_kg_s"]
    return latest


@dataclass(frozen=True)
class BedRenewal:
    """Two equal bed subcells, complementary particle contact histories.

    Only the bottom receives jacket heat. Whole-layer interchange at each
    half-period is a declared ideal circulation, not an identified rake law.
    15 rpm is Mosenthin et al. (2016), a 0.9 m pilot DT, NOT this unit.
    N_mix=2..25 is Tsotsas/Schluender (1986), OTHER granular materials;
    transfer of these scales is an explicit sensitivity assumption.
    """

    mixing_number: float
    sweep_rpm: float = 15.0

    def __post_init__(self):
        for value in (self.mixing_number, self.sweep_rpm):
            if isinstance(value, bool) or not math.isfinite(value) or value <= 0:
                raise ValueError("bed renewal inputs must be finite and positive")

    @property
    def period_s(self):
        return self.mixing_number * 60 / self.sweep_rpm

    def bottom_member(self, elapsed_s):
        if elapsed_s < 0 or not math.isfinite(elapsed_s):
            raise ValueError("bed elapsed time must be finite and nonnegative")
        return int(math.floor(elapsed_s / (self.period_s / 2))) % 2

    def heat_inputs(self, elapsed_s, temperatures_k, reference=PdReference()):
        if len(temperatures_k) != 2 or not all(math.isfinite(v) for v in temperatures_k):
            raise ValueError("two finite bed member temperatures required")
        bottom = self.bottom_member(elapsed_s)
        heater = [0.0, 0.0]
        heater[bottom] = 2 * reference.mean_duty_w_kg_dry
        coefficient = reference.bed_conductivity_w_m_k / (
            reference.bed_dry_density_kg_m3 * (reference.bed_depth_m / 2) ** 2
        )
        out_of_zero = coefficient * (temperatures_k[0] - temperatures_k[1])
        conduction = [-out_of_zero, out_of_zero]
        return dict(
            bottom_member=bottom,
            heater_w_kg_dry=heater,
            conduction_w_kg_dry=conduction,
            net_w_kg_dry=[math.fsum((q, c)) for q, c in zip(heater, conduction)],
        )


class PdPhaseRefused(RuntimeError):
    """The declared surface topology cannot produce an admissible step."""


class WaterAppearanceDemanded(PdPhaseRefused):
    pass


class BedBoilingDemanded(PdPhaseRefused):
    pass


class PrescribedPdFeed(feed.FeedMarch):
    """Canonical uniform-body balances with a declared PD gas/heat boundary.

    Reuses native phase, film, caloric and ONE-CELL Fourier laws. The added
    absent-water coordinates enforce N_water=0 and hexane phase equilibrium;
    they do not force a two-liquid interface onto a surface without water.
    No added thermal resistance, uptake clamp, target removal or radial feed.
    """

    def __init__(
        self,
        bath,
        source,
        *,
        forcing_timescale_s,
        transport_mode,
        bed_boiling=False,
        water_film_energy="body",
    ):
        if water_film_energy not in ("body", "surface"):
            raise ValueError("external water energy must use body or surface temperature")
        self.water_film_energy = water_film_energy
        if not isinstance(bed_boiling, bool):
            raise ValueError("bed_boiling must be an explicit boolean")
        reference = PdReference(**source["reference"])
        super().__init__(
            bath,
            0.0015,
            64,
            pressure_pa=reference.pressure_pa,
            property_parameters=ParticleModelParameters(),
        )
        self.source = MappingProxyType(dict(source))
        self.reference = reference
        self.transport_mode = transport_mode
        self.bed_boiling = bed_boiling
        self.pd_pair = pd_film_pair(source, transport_mode=transport_mode)
        self.forcing_timescale_s = forcing_timescale_s
        self.pd_boundary = core.reduced_film_boundary(
            temperature_k=source["temperature_k"],
            y_hexane=source["y_hexane"],
            pair=self.pd_pair,
            forcing_timescale_s=forcing_timescale_s,
            label="offline equilibrium-generated PD vapour; prescribed continuous withdrawal",
        )
        self.net_heat_w_kg_dry = reference.mean_duty_w_kg_dry
        self.two_liquid_trace = (self.ti, self.yi)
        self.pure_hexane_temperature_k = brentq(
            lambda t: math.log(
                core.bg.state(t, self.pressure, 0.0, 1.0).fugacity_hexane_pa
                / core.hx.state_Tp(t, self.pressure, "liquid").fugacity
            ),
            self.wet.T_min + 1e-4,
            self.wet.T_max - 1e-4,
            xtol=1e-11,
        )
        self.active_surface = "hexane_only"
        self.phase_attempts = []

    def external_water_energy_j(
        self, water_mass_kg, body_temperature_k, *, surface_temperature_k=None
    ):
        if self.water_film_energy == "body":
            return super().external_water_energy_j(water_mass_kg, body_temperature_k)
        temperature = self.ti if surface_temperature_k is None else surface_temperature_k
        return water_mass_kg * core.wa.state_Tp(temperature, self.pressure, "liquid").u_mass

    def interface(self, temperature, total_mass_flux, clock):
        if self.time >= self.pd_end:
            return super().interface(temperature, total_mass_flux, clock)
        tb, yb = self.source["temperature_k"], self.source["y_hexane"]
        contact = self.pd_contact_fraction
        area = self.area * contact
        pair = self.pd_pair
        coefficients = kernel.NativeFilmCoefficients(
            self.source["total_flow_kg_s"],
            pair.state.gas_density_kg_m3,
            pair.state.gas_superficial_velocity_m_s,
            pair.state.bulk_binary_diffusivity_m2_s,
            pair.reynolds_voidage,
            pair.prandtl,
            pair.schmidt,
            pair.nusselt_voidage,
            pair.heat_transfer_w_m2_k,
            pair.binary_mass_transfer_m_s,
            self.pressure / (core.bg.R * tb) * pair.binary_mass_transfer_m_s,
        )
        # Pure-kernel field carriers, exactly as the canonical FeedMarch;
        # these are never presented as host-issued accepted packets.
        basis = SimpleNamespace(
            request=SimpleNamespace(
                hexane_access_oracle=feed.HexaneAccessOracle.TRANSPARENT_INTERFACE
            ),
            complete=SimpleNamespace(state=SimpleNamespace(temperature_k=float(temperature))),
            packets=(SimpleNamespace(pressure_pa=self.pressure),),
            active_area_m2=area,
            dry_mass_fraction=contact,
        )
        native = kernel._group_trial(
            basis,
            model=self.model_view,
            coefficients=coefficients,
            bulk_temperature_k=tb,
            bulk_hexane_mole_fraction=yb,
            local_hydraulic_pressure_pa=self.pressure,
            shared_wall_temperature_k=self.ti,
            interface_temperature_k=self.ti,
            interface_hexane_mole_fraction=self.yi,
            total_molar_flux_mol_m2_s=0.0,
            codec=self.codec_view,
        )
        ref = core.ct.prepare_reduced_film_surface_state(
            self.pd_boundary,
            cell_temperature_k=float(temperature),
            pressure_pa=self.pressure,
            particle_radius_m=self.radius,
            outer_half_cell_distance_m=0.5 * self.radius,
            particle_thermal_conductivity_w_m_k=core.CONDUCTIVITY,
            binary_gas_interaction_k_wh=self.pd_boundary.binary_gas_interaction_k_wh,
        )
        film = core.ct._reduced_film_coefficients_at_surface_temperature(ref, self.ti)
        capacities = core.efr.phy053_partial_enthalpy_secant_heat_capacities(
            surface_temperature_k=self.ti,
            bulk_temperature_k=tb,
            pressure_pa=self.pressure,
            y_hexane=self.yi,
        )
        fluxes = core.efr.component_fluxes_for_supplied_total_mass_flux(
            film,
            total_mass_flux_kg_m2_s=total_mass_flux,
            interface_hexane_mass_fraction=core._hexane_mass_fraction(self.yi),
            bulk_hexane_mass_fraction=core._hexane_mass_fraction(yb),
        )
        nh, nw = fluxes.hexane_kg_m2_s / core.hx.M, fluxes.water_kg_m2_s / core.wa.M
        ack = core.efr.ackermann_heat_transfer(
            film,
            fluxes=fluxes,
            water_film_heat_capacity_j_kg_k=capacities.water_j_kg_k,
            hexane_film_heat_capacity_j_kg_k=capacities.hexane_j_kg_k,
            enforce_production_domain=False,
        )
        qgas = area * film.heat_transfer_w_m2_k * ack.factor * (tb - self.ti)
        phase = area * math.fsum(
            (
                nh
                * (
                    native.native_hexane_partial_enthalpy_j_mol
                    - native.native_hexane_liquid_internal_energy_j_mol
                ),
                nw
                * (
                    native.native_water_partial_enthalpy_j_mol
                    - native.native_water_liquid_internal_energy_j_mol
                ),
            )
        )
        residual = math.fsum((qgas, native.particle_to_interface_w, -phase))
        native = replace(
            native,
            hexane_molar_flux_mol_m2_s=nh,
            water_molar_flux_mol_m2_s=nw,
            total_molar_flux_mol_m2_s=nh + nw,
            raw_hexane_molar_flux_mol_m2_s=nh,
            gas_to_interface_w=qgas,
            interface_energy_residual_w=residual,
            interface_energy_residual_scaled=residual
            / max(abs(qgas), abs(native.particle_to_interface_w), abs(phase), 1.0),
        )
        out = math.fsum(
            (
                area * nh * native.native_hexane_partial_enthalpy_j_mol,
                area * nw * native.native_water_partial_enthalpy_j_mol,
                -qgas,
                -self.net_heat_w_kg_dry * self.dry,
            )
        )
        return native, ack, residual, out, tb, yb, area

    def _trial(self, requested_dt, topology, event=None, *, boiling=False):
        old = self.state
        has_water = topology == "two_liquid"
        if boiling and has_water:
            raise PdPhaseRefused(
                "bed boiling with external water requires the native co-boiling branch"
            )
        latest = {}
        # Coordinates preserve the canonical body/inventory/total-flux rows.
        # Only absent inventories are eliminated; phase traces add equality rows.
        names = [] if boiling else ["temperature"]
        if event != "hexane_depletion":
            names.append("attached")
        if has_water and event != "water_depletion":
            names.append("water")
        names.append("flux")
        if not has_water:
            names.extend(("ti", "yi"))
        if event:
            names.append("dt")
        bulk_hg = (
            nc.hexane_partial_enthalpy(
                self.pure_hexane_temperature_k, self.pressure, 1.0
            ).value_j_mol
            / core.hx.M
        )
        if boiling:
            names.append("boiled_loading")
        seeds = dict(
            temperature=old.temperature_k,
            attached=old.attached_hexane_mass_kg / self.dry,
            water=self.free_water / self.dry + 1e-4,
            flux=0.2,
            ti=self.source["temperature_k"],
            yi=self.source["y_hexane"],
            dt=requested_dt / 2,
            boiled_loading=max(0.0, self.net_heat_w_kg_dry)
            * requested_dt
            / (
                bulk_hg
                - core.hx.state_Tp(self.pure_hexane_temperature_k, self.pressure, "liquid").u_mass
            ),
        )
        lower = dict(
            temperature=self.wet.T_min + 1e-4,
            attached=0.0,
            water=0.0,
            flux=-100.0,
            ti=self.two_liquid_trace[0],
            yi=0.5,
            dt=1e-9,
            boiled_loading=0.0,
        )
        upper = dict(
            temperature=self.wet.T_max - 1e-4,
            attached=1.0,
            water=1.0,
            flux=100.0,
            ti=self.pure_hexane_temperature_k,
            yi=1 - 1e-10,
            dt=requested_dt,
            boiled_loading=old.total_hexane_loading,
        )

        def evaluate(x):
            values = dict(zip(names, map(float, x)))
            # Active phase equality, not clipping a solved superheated state.
            # The additional outflow must close the full mass/energy rows.
            temperature = self.pure_hexane_temperature_k if boiling else values["temperature"]
            attached = values.get("attached", 0.0)
            water = values.get("water", 0.0) * self.dry
            dt = values.get("dt", requested_dt)
            ti, yi = self.two_liquid_trace if has_water else (values["ti"], values["yi"])
            state = core.sphere.initialize_qualified_feed(
                self.params,
                total_hexane_loading=core.sphere.critical_loading(temperature, self.params)
                + attached,
                temperature_k=temperature,
                retained_water_loading=old.retained_water_loading,
                oil_fraction=old.oil_fraction,
            )
            energy = state.total_internal_energy_j + self.external_water_energy_j(
                water, temperature, surface_temperature_k=ti
            )
            previous = self.ti, self.yi
            try:
                self.ti, self.yi = ti, yi
                native, ack, interface_e, out, tb, yb, area = self.interface(
                    temperature, values["flux"], self.time + dt
                )
            finally:
                self.ti, self.yi = previous
            boiled_kg = values.get("boiled_loading", 0.0) * self.dry
            boiling_out_w = boiled_kg / dt * bulk_hg
            out += boiling_out_w
            residuals = [
                state.total_hexane_loading
                - old.total_hexane_loading
                + dt * area / self.dry * native.hexane_molar_flux_mol_m2_s * core.hx.M
                + boiled_kg / self.dry,
                (water - self.free_water + dt * area * native.water_molar_flux_mol_m2_s * core.wa.M)
                / self.dry,
                (energy - self.total_energy + dt * out) / (self.dry * 2e5),
                interface_e / (self.area * 1e4),
            ]
            balance_residuals = np.array(residuals)
            gas = core.bg.state(ti, self.pressure, 1 - yi, yi)
            h_ratio = (
                gas.fugacity_hexane_pa / core.hx.state_Tp(ti, self.pressure, "liquid").fugacity
            )
            w_ratio = gas.fugacity_water_pa / core.wa.state_Tp(ti, self.pressure, "liquid").fugacity
            if not has_water:
                # The absent stock has no inventory coordinate. Enforce its
                # ZERO FLUX directly in the native film-conductance units;
                # the unscaled original balance gate is still checked below.
                # Scaling by dt here would make the phase selection degenerate
                # as dt tends to zero. No balance tolerance is weakened.
                conductance = (
                    self.pd_pair.state.gas_density_kg_m3 * self.pd_pair.binary_mass_transfer_m_s
                )
                residuals[1] = native.water_molar_flux_mol_m2_s * core.wa.M / conductance
                residuals.append(math.log(h_ratio))
            latest.update(
                state=state,
                water=water,
                energy=energy,
                dt=dt,
                native=native,
                ack=ack,
                energy_out=out,
                tb=tb,
                yb=yb,
                active_area=area,
                ti=ti,
                yi=yi,
                h_fugacity_ratio=h_ratio,
                w_fugacity_ratio=w_ratio,
                surface=topology,
                event=event,
                residual=np.array(residuals),
                balance_residuals=balance_residuals,
                bed_boiling_hexane_kg=boiled_kg,
                bed_boiling_energy_out_w=boiling_out_w,
                bed_boiling_active=boiling,
            )
            return latest["residual"]

        solution = least_squares(
            evaluate,
            [seeds[k] for k in names],
            bounds=([lower[k] for k in names], [upper[k] for k in names]),
            x_scale="jac",
            xtol=1e-14,
            ftol=1e-14,
            gtol=None,
            max_nfev=150,
            jac="3-point",
        )
        residual = evaluate(solution.x)
        if (
            not solution.success
            or max(abs(residual)) > 1e-10
            or max(abs(latest["balance_residuals"])) > 1e-10
        ):
            error = PdPhaseRefused(f"{topology}/{event} closure refuses: {max(abs(residual)):.8g}")
            error.details = dict(
                residual=residual.tolist(),
                balance_residual=latest["balance_residuals"].tolist(),
                coordinates=solution.x.tolist(),
                nfev=solution.nfev,
                status=solution.status,
            )
            raise error
        if abs(latest["ack"].beta) > 3.0:
            raise PdPhaseRefused(f"outside unchanged signed Ackermann band: {latest['ack'].beta}")
        if (
            self.bed_boiling
            and not boiling
            and latest["state"].temperature_k > self.pure_hexane_temperature_k
        ):
            raise BedBoilingDemanded(
                "sensible candidate requires the separate native bed-boiling channel"
            )
        if not has_water and latest["w_fugacity_ratio"] > 1.0:
            raise WaterAppearanceDemanded("absent-water surface requires water appearance")
        if (
            has_water
            and self.free_water == 0
            and (latest["water"] <= 0 or latest["native"].water_molar_flux_mol_m2_s >= 0)
        ):
            raise PdPhaseRefused("two-liquid appearance requires positive water and inward flux")
        if event == "water_depletion" and latest["native"].water_molar_flux_mol_m2_s <= 0:
            raise PdPhaseRefused("water depletion lacks outward water flux")
        if event == "hexane_depletion" and latest["native"].hexane_molar_flux_mol_m2_s <= 0:
            raise PdPhaseRefused("hexane depletion lacks outward hexane flux")
        increments = latest["dt"] * np.array(
            (
                latest["active_area"] * latest["native"].hexane_molar_flux_mol_m2_s * core.hx.M
                + latest["bed_boiling_hexane_kg"] / latest["dt"],
                latest["active_area"] * latest["native"].water_molar_flux_mol_m2_s * core.wa.M,
                latest["energy_out"],
            )
        )
        cumulative = self.cumulative + increments
        actual = np.array((latest["state"].total_hexane_mass_kg, latest["water"], latest["energy"]))
        ledger = actual - np.array(self.initial) + cumulative
        scales = np.array(
            (
                max(self.initial[0], actual[0], abs(cumulative[0])),
                self.dry * old.retained_water_loading + max(actual[1], abs(cumulative[1])),
                self.dry * 2e5,
            )
        )
        normalized = abs(ledger) / scales
        if max(normalized) > 1e-10:
            raise PdPhaseRefused(
                f"cumulative component/energy ledger refuses: {normalized.tolist()}"
            )
        latest.update(
            normalized_cumulative_ledger=normalized.tolist(),
            ledger=ledger,
            cumulative=cumulative,
            nfev=solution.nfev,
            owner=self,
            start_state=old,
            start_time=self.time,
            net_heat=self.net_heat_w_kg_dry,
        )
        return latest

    def trial(self, requested_dt, event=False):
        """Select a physical trial without committing, for synchronized bed members."""
        if (
            not math.isfinite(requested_dt)
            or requested_dt <= 0
            or self.time + requested_dt > self.pd_end + 1e-12
        ):
            raise ValueError("positive PD step must land before its prescribed boundary")
        topology = "two_liquid" if self.free_water > 0 else "hexane_only"
        attempts = []
        candidates = []
        specifications = [(topology, "hexane_depletion" if event else None)]
        if self.free_water == 0 and not event:
            specifications.append(("two_liquid", None))
        for mode, kind in specifications:
            try:
                candidates.append(self._trial(requested_dt, mode, kind))
                break
            except BedBoilingDemanded as exc:
                attempts.append(dict(surface=mode, event=kind, error=str(exc)))
                candidates.append(self._trial(requested_dt, mode, kind, boiling=True))
                break
            except PdPhaseRefused as exc:
                attempts.append(dict(surface=mode, event=kind, error=str(exc)))
        if not candidates and self.free_water > 0 and not event:
            try:
                candidates.append(self._trial(requested_dt, "two_liquid", "water_depletion"))
            except PdPhaseRefused as exc:
                attempts.append(dict(surface="two_liquid", event="water_depletion", error=str(exc)))
        if not candidates:
            error = PdPhaseRefused(f"all declared surface candidates refuse: {attempts}")
            error.details = attempts
            raise error
        step = candidates[0]
        step["phase_attempts"] = attempts
        return step

    def commit_trial(self, step):
        """Commit an already checked trial, exactly once."""
        if step.get("committed", False):
            raise ValueError("PD trial already committed")
        if (
            step["owner"] is not self
            or step["start_state"] is not self.state
            or step["start_time"] != self.time
            or step["net_heat"] != self.net_heat_w_kg_dry
        ):
            raise ValueError("PD trial owner, state, time or heat input differs")
        step["committed"] = True
        self.state, self.free_water, self.total_energy = (
            step["state"],
            step["water"],
            step["energy"],
        )
        self.cumulative = step["cumulative"]
        self.ti, self.yi = step["ti"], step["yi"]
        self.active_surface = "hexane_only" if self.free_water == 0 else "two_liquid"
        self.time += step["dt"]
        self.phase_attempts.extend(
            dict(time_s=self.time, **attempt) for attempt in step["phase_attempts"]
        )
        self.rows.append(self.row(step, step["ledger"]))
        return step

    def solve(self, requested_dt, event=False):
        if self.time >= self.pd_end:
            self.ti, self.yi = self.two_liquid_trace
            return super().solve(requested_dt, event=event)
        return self.commit_trial(self.trial(requested_dt, event=event))

    def row(self, step, ledger):
        row = super().row(step, ledger)
        if hasattr(self, "ti"):
            row.update(
                external_water_energy_temperature=self.water_film_energy,
                external_water_temperature_k=(
                    self.ti if self.water_film_energy == "surface" else self.state.temperature_k
                ),
            )
        if hasattr(self, "active_surface"):
            pd_step = step is not None and "bed_boiling_hexane_kg" in step
            row.update(
                surface_topology="two_liquid" if self.free_water > 0 else "hexane_only",
                interface_temperature_k=self.ti,
                interface_y_hexane=self.yi,
                net_indirect_and_bed_heat_w_kg_dry=self.net_heat_w_kg_dry if pd_step else 0.0,
                bed_boiling_active=step.get("bed_boiling_active", False) if step else False,
                bed_boiling_hexane_kg=step.get("bed_boiling_hexane_kg", 0.0) if step else 0.0,
            )
        return row
